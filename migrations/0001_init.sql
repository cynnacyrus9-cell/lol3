-- Roadster Life Analytics — initial schema (Cloudflare D1 / SQLite)
--
-- Conventions
--   * All timestamps are UTC epoch milliseconds (INTEGER).
--   * `day` columns are calendar days (YYYY-MM-DD) in the reporting timezone
--     stored next to them (`tz`), so changing the timezone never corrupts history.
--   * `source` separates real production data ('live') from Roblox Studio test
--     sessions ('studio') and generated development data ('synthetic').
--     Production queries always filter on source = 'live'.
--   * Indexes are deliberately few: on the D1 free plan each index entry is an
--     extra "row written".

-- Non-secret settings editable from the admin panel. Secrets never live here.
CREATE TABLE app_config (
  key        TEXT PRIMARY KEY,
  value      TEXT NOT NULL,
  updated_at INTEGER NOT NULL
) WITHOUT ROWID;

-- Developer products and game passes (configured by the owner or resolved in-game
-- through MarketplaceService:GetProductInfo).
CREATE TABLE products (
  kind          TEXT NOT NULL CHECK (kind IN ('developer_product', 'game_pass')),
  product_id    INTEGER NOT NULL CHECK (product_id > 0),
  name          TEXT,
  price_robux   INTEGER CHECK (price_robux IS NULL OR price_robux >= 0),
  configured    INTEGER NOT NULL DEFAULT 0, -- 1 = entered by the owner in the admin panel
  info_source   TEXT,                       -- 'owner' | 'game_server'
  updated_at    INTEGER NOT NULL,
  PRIMARY KEY (kind, product_id)
) WITHOUT ROWID;

-- Verified purchases. `dedupe_key` makes ingestion idempotent:
--   developer products: 'dp:<PurchaseId>'          (Roblox receipt PurchaseId)
--   game passes:        'gp:<UserId>:<GamePassId>'  (a pass can be owned once)
CREATE TABLE purchases (
  id               INTEGER PRIMARY KEY,
  dedupe_key       TEXT NOT NULL UNIQUE,
  kind             TEXT NOT NULL CHECK (kind IN ('developer_product', 'game_pass')),
  product_id       INTEGER NOT NULL,
  product_name     TEXT,
  robux            INTEGER NOT NULL CHECK (robux >= 0),
  amount_source    TEXT NOT NULL CHECK (amount_source IN ('receipt', 'list_price')),
  user_id          INTEGER,
  username         TEXT,
  job_id           TEXT,
  place_id         INTEGER,
  purchase_id      TEXT,
  currency_type    TEXT,
  purchased_at     INTEGER NOT NULL,
  received_at      INTEGER NOT NULL,
  source           TEXT NOT NULL DEFAULT 'live' CHECK (source IN ('live', 'studio', 'synthetic'))
);
CREATE INDEX idx_purchases_source_time ON purchases (source, purchased_at);

-- One row per player visit observed by the in-game integration.
-- session_id = '<JobId>:<UserId>:<JoinedAtMs>' is generated by the game server,
-- so repeated join reports, heartbeat reconciliation and retries are idempotent.
CREATE TABLE player_sessions (
  session_id   TEXT PRIMARY KEY,
  user_id      INTEGER NOT NULL,
  username     TEXT,
  job_id       TEXT NOT NULL,
  place_id     INTEGER,
  started_at   INTEGER NOT NULL,
  ended_at     INTEGER,
  duration_sec INTEGER,
  end_reason   TEXT CHECK (end_reason IS NULL OR end_reason IN ('left', 'server_shutdown', 'server_timeout')),
  join_source  TEXT NOT NULL DEFAULT 'event' CHECK (join_source IN ('event', 'reconciled')),
  source       TEXT NOT NULL DEFAULT 'live' CHECK (source IN ('live', 'studio', 'synthetic'))
) WITHOUT ROWID;
CREATE INDEX idx_sessions_source_started ON player_sessions (source, started_at);
CREATE INDEX idx_sessions_source_ended ON player_sessions (source, ended_at) WHERE ended_at IS NOT NULL;

-- Distinct players per reporting day (exact unique-player counts).
CREATE TABLE daily_players (
  tz      TEXT NOT NULL,
  day     TEXT NOT NULL,
  user_id INTEGER NOT NULL,
  source  TEXT NOT NULL DEFAULT 'live',
  PRIMARY KEY (tz, day, source, user_id)
) WITHOUT ROWID;

-- Game server lifetimes (uptime, open/close events, crash detection).
CREATE TABLE server_sessions (
  job_id                 TEXT PRIMARY KEY,
  place_id               INTEGER,
  place_version          INTEGER,
  private_server         INTEGER NOT NULL DEFAULT 0,
  started_at             INTEGER NOT NULL,
  last_seen_at           INTEGER NOT NULL,
  ended_at               INTEGER,
  end_reason             TEXT CHECK (end_reason IS NULL OR end_reason IN ('shutdown', 'heartbeat_timeout')),
  peak_players           INTEGER NOT NULL DEFAULT 0,
  source                 TEXT NOT NULL DEFAULT 'live' CHECK (source IN ('live', 'studio', 'synthetic'))
) WITHOUT ROWID;
CREATE INDEX idx_servers_source_started ON server_sessions (source, started_at);

-- Activity feed. `seq` is assigned by the Durable Object and is strictly increasing,
-- which lets reconnecting dashboards request exactly the events they missed.
CREATE TABLE activity_events (
  seq         INTEGER PRIMARY KEY,
  type        TEXT NOT NULL,
  category    TEXT NOT NULL CHECK (category IN ('players', 'sales', 'servers', 'milestones')),
  occurred_at INTEGER NOT NULL,
  data        TEXT NOT NULL,
  source      TEXT NOT NULL DEFAULT 'live' CHECK (source IN ('live', 'studio', 'synthetic'))
);
CREATE INDEX idx_activity_category_seq ON activity_events (category, seq);

-- One row per minute while tracking is active.
CREATE TABLE ccu_snapshots (
  minute_at    INTEGER PRIMARY KEY, -- UTC ms aligned to the minute
  tracked_ccu  INTEGER NOT NULL,    -- players at the end of the minute (in-game events)
  tracked_max  INTEGER NOT NULL,    -- highest player count seen during the minute
  servers      INTEGER NOT NULL,
  official_ccu INTEGER,             -- Roblox "playing" count if polled during the minute
  source       TEXT NOT NULL DEFAULT 'live' CHECK (source IN ('live', 'synthetic'))
);

-- Official Roblox counters (games.roblox.com). Written when a value changes and at
-- least hourly so day boundaries can be resolved.
CREATE TABLE official_snapshots (
  fetched_at INTEGER PRIMARY KEY,
  visits     INTEGER,
  playing    INTEGER,
  favorites  INTEGER
);

-- Finalised / periodically recomputed daily totals. Recomputed from the raw tables,
-- never incremented, so duplicates and late events cannot inflate them.
CREATE TABLE daily_aggregates (
  tz                   TEXT NOT NULL,
  day                  TEXT NOT NULL,
  revenue_robux        INTEGER NOT NULL DEFAULT 0,
  sales_count          INTEGER NOT NULL DEFAULT 0,
  dev_product_revenue  INTEGER NOT NULL DEFAULT 0,
  dev_product_sales    INTEGER NOT NULL DEFAULT 0,
  game_pass_revenue    INTEGER NOT NULL DEFAULT 0,
  game_pass_sales      INTEGER NOT NULL DEFAULT 0,
  tracked_visits       INTEGER NOT NULL DEFAULT 0,
  unique_players       INTEGER NOT NULL DEFAULT 0,
  peak_ccu             INTEGER NOT NULL DEFAULT 0,
  avg_ccu              REAL,
  sessions_ended       INTEGER NOT NULL DEFAULT 0,
  avg_session_sec      REAL,
  official_visits_start INTEGER,
  official_visits_end   INTEGER,
  tracked_minutes      INTEGER NOT NULL DEFAULT 0,
  finalized            INTEGER NOT NULL DEFAULT 0,
  updated_at           INTEGER NOT NULL,
  PRIMARY KEY (tz, day)
) WITHOUT ROWID;
